-- 1. Academic Years Table
CREATE TABLE IF NOT EXISTS academic_years (
    academic_year_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year_label VARCHAR(50) NOT NULL UNIQUE,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL
);

-- 2. Faculties Table
CREATE TABLE IF NOT EXISTS faculties (
    faculty_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_name VARCHAR(150) NOT NULL UNIQUE,
    department VARCHAR(150) NOT NULL
);

-- 3. Users Table
CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 4. Students Table
CREATE TABLE IF NOT EXISTS students (
    student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    faculty_id BIGINT REFERENCES faculties(faculty_id) ON DELETE SET NULL,
    academic_year_id BIGINT REFERENCES academic_years(academic_year_id) ON DELETE SET NULL
);

-- 5. Tuition Fees Structure (For Academic & Finance Modules)
CREATE TABLE IF NOT EXISTS tuition_fees (
    fee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id BIGINT REFERENCES faculties(faculty_id) ON DELETE CASCADE,
    academic_year_id BIGINT REFERENCES academic_years(academic_year_id) ON DELETE CASCADE,
    semester VARCHAR(20) NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    description VARCHAR(255)
);

-- 6. Invoices Table (For Student Tuition Billing)
CREATE TABLE IF NOT EXISTS invoices (
    invoice_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number VARCHAR(50) NOT NULL UNIQUE,
    student_id BIGINT NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
    amount NUMERIC(10, 2) NOT NULL,
    issue_date DATE NOT NULL,
    due_date DATE NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING'
);

-- 7. Payments Table (For KHQR / Bakong / ABA / Cash Payments)
CREATE TABLE IF NOT EXISTS payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES invoices(invoice_id) ON DELETE CASCADE,
    transaction_reference VARCHAR(100) NOT NULL UNIQUE,
    payment_method VARCHAR(50) NOT NULL,
    amount_paid NUMERIC(10, 2) NOT NULL,
    payment_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(30) NOT NULL DEFAULT 'SUCCESS'
);

-- Helpful Indexes for Query and Filtering Performance
CREATE INDEX IF NOT EXISTS idx_users_role ON users(role);
CREATE INDEX IF NOT EXISTS idx_students_faculty ON students(faculty_id);
CREATE INDEX IF NOT EXISTS idx_students_year ON students(academic_year_id);
CREATE INDEX IF NOT EXISTS idx_invoices_student ON invoices(student_id);
CREATE INDEX IF NOT EXISTS idx_invoices_status ON invoices(status);
CREATE INDEX IF NOT EXISTS idx_payments_invoice ON payments(invoice_id);
