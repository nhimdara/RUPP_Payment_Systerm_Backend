CREATE INDEX IF NOT EXISTS idx_users_role ON users(role);
CREATE INDEX IF NOT EXISTS idx_students_user ON students(user_id);
CREATE INDEX IF NOT EXISTS idx_students_faculty ON students(faculty_id);
CREATE INDEX IF NOT EXISTS idx_students_year ON students(academic_year_id);
CREATE INDEX IF NOT EXISTS idx_students_major ON students(major_id);
CREATE INDEX IF NOT EXISTS idx_majors_faculty ON majors(faculty_id);
CREATE INDEX IF NOT EXISTS idx_fee_faculty_year ON tuition_fee_structures(faculty_id, academic_year_id);
CREATE INDEX IF NOT EXISTS idx_payments_student ON payments(student_id);
CREATE INDEX IF NOT EXISTS idx_payments_fee ON payments(fee_structure_id);
CREATE INDEX IF NOT EXISTS idx_payments_status_date ON payments(payment_status, payment_date);
CREATE INDEX IF NOT EXISTS idx_payments_date ON payments(payment_date);
CREATE INDEX IF NOT EXISTS idx_details_payment ON payment_details(payment_id);
CREATE INDEX IF NOT EXISTS idx_details_method ON payment_details(method);
CREATE INDEX IF NOT EXISTS idx_receipts_payment ON receipts(payment_id);
CREATE INDEX IF NOT EXISTS idx_receipts_number ON receipts(receipt_number);
CREATE INDEX IF NOT EXISTS idx_receipts_issue_date ON receipts(issue_date);
CREATE INDEX IF NOT EXISTS idx_audit_payment ON payment_audit_logs(payment_id);
CREATE INDEX IF NOT EXISTS idx_audit_actor ON payment_audit_logs(actor_user_id);
CREATE INDEX IF NOT EXISTS idx_audit_created ON payment_audit_logs(created_at);
