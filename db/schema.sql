-- 1. User Table
CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    role VARCHAR(30) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Faculty Table
CREATE TABLE IF NOT EXISTS faculties (
    faculty_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_name VARCHAR(150) NOT NULL UNIQUE,
    department VARCHAR(150) NOT NULL
);

-- 3. Major Table
CREATE TABLE IF NOT EXISTS majors (
    major_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    major_name VARCHAR(150) NOT NULL,
    major_code VARCHAR(50) NOT NULL UNIQUE,
    faculty_id BIGINT REFERENCES faculties(faculty_id) ON DELETE SET NULL,
    description VARCHAR(500)
);

-- 4. Academic Year Table
CREATE TABLE IF NOT EXISTS academic_years (
    academic_year_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year_label VARCHAR(50) NOT NULL UNIQUE,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL
);

-- 5. Semester Table
CREATE TABLE IF NOT EXISTS semesters (
    semester_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_name VARCHAR(50) NOT NULL,
    academic_year_id BIGINT NOT NULL REFERENCES academic_years(academic_year_id) ON DELETE CASCADE
);

-- 6. Student Table
CREATE TABLE IF NOT EXISTS students (
    student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    faculty_id BIGINT REFERENCES faculties(faculty_id) ON DELETE SET NULL,
    academic_year_id BIGINT REFERENCES academic_years(academic_year_id) ON DELETE SET NULL,
    major_id BIGINT REFERENCES majors(major_id) ON DELETE SET NULL
);

-- 7. Tuition Fee Structure Table
CREATE TABLE IF NOT EXISTS tuition_fee_structures (
    fee_structure_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id BIGINT NOT NULL REFERENCES faculties(faculty_id) ON DELETE CASCADE,
    academic_year_id BIGINT NOT NULL REFERENCES academic_years(academic_year_id) ON DELETE CASCADE,
    total_amount NUMERIC(10, 2) NOT NULL,
    due_date DATE NOT NULL,
    CONSTRAINT uq_db_fee_faculty_year UNIQUE (faculty_id, academic_year_id)
);

-- 8. Payment Status Table
CREATE TABLE IF NOT EXISTS payment_statuses (
    payment_status_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_name VARCHAR(50) NOT NULL UNIQUE
);

-- 9. Payment Table
CREATE TABLE IF NOT EXISTS payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(student_id) ON DELETE CASCADE,
    fee_structure_id BIGINT NOT NULL REFERENCES tuition_fee_structures(fee_structure_id) ON DELETE CASCADE,
    payment_status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    payment_status_id BIGINT REFERENCES payment_statuses(payment_status_id) ON DELETE SET NULL,
    payment_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    total_paid NUMERIC(10, 2) NOT NULL,
    remarks VARCHAR(500)
);

-- 10. Payment Detail Table
CREATE TABLE IF NOT EXISTS payment_details (
    payment_detail_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL REFERENCES payments(payment_id) ON DELETE CASCADE,
    method VARCHAR(50) NOT NULL,
    transaction_ref VARCHAR(100) NOT NULL UNIQUE,
    amount NUMERIC(10, 2) NOT NULL
);

-- 11. Receipt Table
CREATE TABLE IF NOT EXISTS receipts (
    receipt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL UNIQUE REFERENCES payments(payment_id) ON DELETE CASCADE,
    receipt_number VARCHAR(100) NOT NULL UNIQUE,
    issue_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    total_amount NUMERIC(10, 2) NOT NULL
);

-- 12. Payment Audit Logs Table
CREATE TABLE IF NOT EXISTS payment_audit_logs (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL,
    action VARCHAR(50) NOT NULL,
    from_status VARCHAR(30),
    to_status VARCHAR(30),
    actor_user_id BIGINT,
    actor_username VARCHAR(100),
    actor_role VARCHAR(50),
    details VARCHAR(1000),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

